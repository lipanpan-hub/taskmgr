import {mkdirSync, writeFileSync} from 'node:fs'
import {join} from 'node:path'
import {getOclifConfigDir} from '../utils/oclif-config-dir.js'

export interface HiddenTaskInput {
  executablePath: string
  arguments: string
}

// 通过 wscript 启动器隐藏控制台窗口运行命令
// wscript.exe 是 GUI 程序, 被任务计划程序拉起时不分配控制台; 启动器再以窗口样式 0 启动目标命令并等待其结束, 退出码原样交回任务计划程序
// 启动器用 JScript 而非 VBScript: 微软已计划在 2027 年左右默认禁用 VBScript
export class HiddenLauncher {
  private static readonly FILE_NAME = 'hidden-launcher.js'
  // 内容必须是纯 ASCII: wscript 按 ANSI(GBK) 解码无 BOM 文件, 中文注释会吞掉换行导致脚本出错
  private static readonly SCRIPT_CONTENT = [
    '// Generated by tm. Run the given command line with a hidden window and return its exit code.',
    'var argList = [];',
    'for (var i = 0; i < WScript.Arguments.length; i++) {',
    '  var arg = WScript.Arguments(i);',
    "  argList.push(((arg === '') || (arg.indexOf(' ') >= 0)) ? ('\"' + arg + '\"') : arg);",
    '}',
    "WScript.Quit(new ActiveXObject('WScript.Shell').Run(argList.join(' '), 0, true));",
    '',
  ].join('\n')

  // 写入启动器并返回绝对路径; 每次运行 tm 都重写, 文件被清理工具删除后可自愈
  static ensure(): string {
    const configDir = getOclifConfigDir()
    mkdirSync(configDir, {recursive: true})
    const launcherPath = join(configDir, HiddenLauncher.FILE_NAME)
    writeFileSync(launcherPath, HiddenLauncher.SCRIPT_CONTENT, {encoding: 'utf8'})
    return launcherPath
  }

  // 生成隐藏运行 PowerShell 脚本的任务输入, runtimeExe 为 powershell.exe 或 pwsh.exe
  // 仍需 -WindowStyle Hidden: 窗口样式 0 只作用于子进程第一次 ShowWindow, 不加时脚本里 Form.Show() 弹出的窗口会被一起隐藏(已实测)
  static forPowerShellScript(runtimeExe: string, scriptPath: string): HiddenTaskInput {
    const launcherPath = HiddenLauncher.ensure()
    return {
      executablePath: 'wscript.exe',
      // //E:JScript 不依赖 .js 文件关联; //B 禁止脚本错误弹窗卡住任务
      arguments: `//E:JScript //B "${launcherPath}" ${runtimeExe} -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "${scriptPath}"`,
    }
  }
}
